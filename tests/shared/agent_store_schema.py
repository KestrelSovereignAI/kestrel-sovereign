"""Content-free snapshots of a released agent database, for upgrade tests (#4002).

A fresh-schema fixture only proves what a new database looks like. #3995 added
columns to a CORE store without a schema revision, so every existing database
skipped them, and every tool call failed once #3999 made the audit required.
CI was green because every test database was born on the new code.

A snapshot holds what a released Core's freshly booted agent database holds,
minus its content: every table, index, trigger and view, and the rows of the
revision tables that decide which upgrades startup runs. Identity, keys,
constitution text and every other row are left out; a test mints its own
identity into the loaded schema.

Capture a release by running this file with that release's code importable,
for example from a detached worktree of its tag::

    env PYTHONPATH=/tmp/core-v0.64.1 python tests/shared/agent_store_schema.py \\
        --release 0.64.1 --output tests/fixtures/agent_store_schema/v0.64.1.sql

It boots one agent with only the mandatory features, so the capture depends
on no installed feature package. It needs ``KESTREL_DATA_KEY`` and
``KESTREL_DID_WEB_DOMAIN`` (any throwaway values) for the born-hybrid
identity. Run it as a file, not with ``-m``: the release's own ``tests``
package must not shadow this one.
"""

from __future__ import annotations

import sqlite3
from pathlib import Path

SNAPSHOT_DIR = Path(__file__).resolve().parents[1] / "fixtures" / "agent_store_schema"

#: Tables whose rows record which schema revisions and migrations the database
#: already crossed. Their rows are the only ones a snapshot keeps.
REVISION_TABLES = (
    "a2a_native_store_schema",
    "a2a_protocol_schema",
    "schema_backfills",
    "semantic_schema_migrations",
    "tool_effect_schema",
)

_HEADER = "-- kestrel-agent-store-schema v1\n"
_OBJECT_ORDER = {"table": 0, "index": 1, "view": 2, "trigger": 3}


def snapshot_path(release: str) -> Path:
    """The committed snapshot of ``release``'s fresh agent database."""
    return SNAPSHOT_DIR / f"v{release}.sql"


def _shadow_tables(connection: sqlite3.Connection) -> set[str]:
    """Virtual-table internals; recreating the virtual table recreates them."""
    return {
        name
        for name, kind in connection.execute(
            "SELECT name, type FROM pragma_table_list WHERE schema = 'main'"
        )
        if kind == "shadow"
    }


def _quote(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return repr(value)
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    raise TypeError(f"A revision row holds a {type(value).__name__}, not a scalar")


def capture(db_path: Path, *, release: str) -> str:
    """The content-free snapshot of the database at ``db_path``."""
    connection = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    try:
        shadows = _shadow_tables(connection)
        objects = [
            (kind, name, sql)
            for kind, name, sql in connection.execute(
                "SELECT type, name, sql FROM sqlite_master "
                "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\' "
                "ORDER BY rowid"
            )
            if name not in shadows
        ]
        objects.sort(key=lambda item: _OBJECT_ORDER[item[0]])
        tables = {name for kind, name, _ in objects if kind == "table"}
        lines = [
            _HEADER,
            f"-- A freshly booted Kestrel Core {release} agent database, without content.\n",
            "-- Generated by tests/shared/agent_store_schema.py; do not edit by hand.\n",
        ]
        lines.extend(f"{sql};\n" for _, _, sql in objects)
        for table in REVISION_TABLES:
            if table not in tables:
                continue
            columns = [row[1] for row in connection.execute(f'PRAGMA table_info("{table}")')]
            names = ", ".join(f'"{column}"' for column in columns)
            for row in connection.execute(
                f'SELECT {names} FROM "{table}" ORDER BY {names}'
            ):
                values = ", ".join(_quote(value) for value in row)
                lines.append(f"INSERT INTO {table} ({names}) VALUES ({values});\n")
        return "".join(lines)
    finally:
        connection.close()


def load(db_path: Path, snapshot: Path) -> None:
    """Create ``db_path`` holding exactly the schema and revision rows of ``snapshot``."""
    text = snapshot.read_text(encoding="utf-8")
    if not text.startswith(_HEADER):
        raise ValueError(f"{snapshot} is not an agent store schema snapshot")
    if db_path.exists():
        raise FileExistsError(f"{db_path} already exists")
    connection = sqlite3.connect(db_path)
    try:
        connection.executescript(text)
    finally:
        connection.close()


async def _capture_booted_release(output: Path, release: str) -> None:
    import os
    import tempfile

    from kestrel_sovereign.inception_service import create_kestrel_identity_async
    from kestrel_sovereign.kestrel_agent import KestrelAgent
    from kestrel_sovereign.llm.service import LLMService

    with tempfile.TemporaryDirectory(prefix="agent-store-schema-") as directory:
        credentials = await create_kestrel_identity_async(
            output_dir=directory, is_test_instance=True, agent_name="SchemaCapture"
        )
        db_path = Path(directory) / "kestrel_prime.db"
        llm_service = LLMService()
        agent = KestrelAgent(
            did=credentials.agent_did,
            storage_path=os.fspath(db_path),
            llm_service=llm_service,
            allowed_features=set(),
        )
        try:
            await agent.initialize()
        finally:
            await agent.shutdown()
            await llm_service.close()
        output.write_text(capture(db_path, release=release), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    import argparse
    import asyncio

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--release", required=True, help="the release being captured")
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args(argv)
    asyncio.run(_capture_booted_release(args.output, args.release))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
