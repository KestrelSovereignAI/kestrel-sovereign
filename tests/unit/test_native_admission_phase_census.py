def test_all_unphased_native_admissions_match_the_reviewed_role_census():
    expected = Counter()
    for row in _CLASSIFIED.strip().splitlines():
        role, relative, function, callee = (column.strip() for column in row.split("|"))
        assert role in {"WORK", "DELEGATE", "DETACHED", "BROKER_WORK", "INHERITED"}
        expected[relative, function, callee] += 1
    package = Path(__file__).resolve().parents[2] / "kestrel_sovereign"
    actual = Counter()
    for path in sorted(package.rglob("*.py")):
        visitor = _AdmissionPhases()
        visitor.visit(ast.parse(path.read_text(), filename=str(path)))
        for function, callee, phased, _ in visitor.calls:
            if callee in {"create_owned_task", "OwnedOperation", "await_owned_operation"} and not phased:
                actual[path.relative_to(package).as_posix(), function, callee] += 1
    assert actual == expected, (
        "Unreviewed or rephased native admissions: "
        f"added={actual - expected}; removed/rephased={expected - actual}"
    )


def test_aliased_delivery_creators_keep_work_phase_and_exact_producer_wiring():
    package = Path(__file__).resolve().parents[2] / "kestrel_sovereign"
    tree = ast.parse((package / "features/delivery/queue.py").read_text())
    visitor = _AdmissionPhases()
    visitor.visit(tree)
    creators = [(function, phased) for function, callee, phased, _ in visitor.calls if callee == "factory"]
    assert creators == [("DeliveryQueue.start", False), ("DeliveryQueue.process_pending", False)]
    aliases = [node.value for node in ast.walk(tree)
               if isinstance(node, ast.Assign)
               and any(isinstance(target, ast.Name) and target.id == "factory" for target in node.targets)]
    assert len(aliases) == 2
    for alias in aliases:
        assert isinstance(alias, ast.BoolOp) and isinstance(alias.op, ast.Or)
        assert isinstance(alias.values[-1], ast.Name) and alias.values[-1].id == "create_owned_task"
